    #[test]
    fn provisioner_daemon_status_classification() {
        let key = "ofci-key-a";
        assert!(daemon_matches_online(
            &serde_json::json!([{"key_name": key, "status": "idle", "name": "d1"}]),
            key
        ));
        assert!(daemon_matches_online(
            &serde_json::json!([{"key_name": key, "status": "busy", "name": "d1"}]),
            key
        ));
        assert!(!daemon_matches_online(
            &serde_json::json!([{"key_name": key, "status": "offline", "name": "d1"}]),
            key
        ));
        assert!(!daemon_matches_online(
            &serde_json::json!([{"key_name": "ofci-key-other", "status": "idle", "name": "d1"}]),
            key
        ));
        assert!(!daemon_matches_online(&serde_json::json!([]), key));
    }

    /// Pure mirror of the identity+status logic in `provisioner_daemons_ready`.
    fn daemon_matches_online(daemons: &Value, key_name: &str) -> bool {
        daemons
            .as_array()
            .map(|arr| {
                arr.iter().any(|d| {
                    d.get("key_name").and_then(Value::as_str) == Some(key_name)
                        && matches!(
                            d.get("status").and_then(Value::as_str),
                            Some("idle") | Some("busy")
                        )
                })
            })
            .unwrap_or(false)
    }
