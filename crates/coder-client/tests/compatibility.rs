// ── Cleanup (prefix `cleanup_`, explicit, org-scoped) ──────────────────────
// Validates deployment URL and org before deleting, deletes children before
// parents, org-scopes every delete, keeps a provisioner running so the
// Terraform deletion job can execute, and retains entries whose deletion failed.

#[tokio::test]
#[ignore = "deletes resources recorded in the ledger; requires OPENFLOWS_CODER_MUTATE=1"]
async fn cleanup_created_resources() {
    require_mutate();
    let client = require_live_client();
    let deployment = coder_url().expect("CODER_URL");
    let ledger = with_ledger_lock(load_ledger_locked);

    // Only consider entries belonging to THIS deployment and org prefix.
    let candidates: Vec<LedgerEntry> = ledger
        .entries
        .iter()
        .filter(|e| e.deployment_url == deployment && e.org.starts_with(&org_prefix()))
        .cloned()
        .collect();

    // Workspace and template deletion each need a provisioner daemon to run the
    // Terraform deletion job. Spin one up per org that owns any such resource.
    let mut daemons: Vec<tokio::process::Child> = Vec::new();
    let orgs_needing_provisioner: std::collections::BTreeSet<String> = candidates
        .iter()
        .filter(|e| matches!(e.kind.as_str(), "workspace" | "template"))
        .map(|e| e.org.clone())
        .collect();
    for org in &orgs_needing_provisioner {
        // Resolve the org id for the daemon's --org flag from the ledger org
        // entry; fall back to the org name.
        let org_id = candidates
            .iter()
            .find(|e| e.kind == "org" && e.org == *org)
            .map(|e| e.resource_id.clone())
            .filter(|id| !id.is_empty())
            .unwrap_or_else(|| org.clone());
        if read_provisioner_secret(&org_id).is_some() {
            daemons.push(start_provisioner_daemon(&org_id));
        } else {
            println!(
                "cleanup WARN: no stored provisioner daemon secret for org {org}; \
                 deletion jobs for it may remain queued"
            );
        }
    }

    // Child-before-parent deletion order. If a child (workspace/template)
    // deletion fails for an org, its parent dependencies (template, user,
    // provisioner key, org) are recovery dependencies for the pending deletion
    // job and MUST be preserved so a retry can finish. We track failed orgs and
    // skip every later dependency for them.
    let mut failed_orgs: std::collections::BTreeSet<String> = std::collections::BTreeSet::new();
    let order: &[&str] = &["workspace", "template", "user", "provisioner_key", "org"];
    for kind in order {
        for entry in candidates.iter().filter(|e| e.kind == *kind) {
            // Preserve all remaining dependencies once an org's deletion failed.
            if failed_orgs.contains(&entry.org) {
                println!(
                    "cleanup SKIP {} {} (org {}): a dependency failed earlier; preserving for retry",
                    kind, entry.id, entry.org
                );
                continue;
            }
            let org_id = candidates
                .iter()
                .find(|e| e.kind == "org" && e.org == entry.org)
                .map(|e| e.resource_id.clone())
                .unwrap_or_default();
            let ok = delete_resource(&client, kind, &entry.id, &entry.org, &org_id).await;
            ledger_delete_result(kind, &entry.id, &entry.resource_id, &entry.org, ok);
            if ok {
                println!("cleanup {} {} (org {})", kind, entry.id, entry.org);
            } else {
                println!(
                    "cleanup FAILED {} {} (org {}); retained for retry and dependencies preserved",
                    kind, entry.id, entry.org
                );
                failed_orgs.insert(entry.org.clone());
            }
        }
    }

    for mut d in daemons {
        stop_provisioner_daemon(&mut d).await;
    }

    // Cleanup is only complete when every candidate is gone. A failed deletion
    // (or a dependency preserved because of one) must fail the command so the
    // caller knows resources remain.
    if !failed_orgs.is_empty() {
        panic!(
            "cleanup INCOMPLETE: deletion failed and dependencies were preserved for org(s) {:?}; \
             re-run --cleanup after the pending deletion job completes.",
            failed_orgs
        );
    }
}

async fn delete_resource(
    client: &CoderClient,
    kind: &str,
    id: &str,
    org: &str,
    org_id: &str,
) -> bool {
    assert_not_default_org(org);
    // Every deletion runs under a wall-clock deadline via `coder_cli_timeout`
    // (which sets kill_on_drop and kills/reaps the child on timeout), so a
    // stalled deletion job or an unreachable provisioner cannot hang cleanup.
    // On timeout the call returns an error, the deletion is marked failed, and
    // the org's dependencies are preserved for retry.
    let timeout = std::time::Duration::from_secs(120);
    match kind {
        "provisioner_key" => match delete_provisioner_key_api(client, org_id, id).await {
            Ok(()) => true,
            Err(e) => {
                println!(
                    "cleanup provisioner_key {} failed: {}",
                    id,
                    redact_string(&e)
                );
                false
            }
        },
        "workspace" => coder_cli_timeout(&["delete", "--yes", id], org, timeout)
            .await
            .is_ok(),
        "template" => coder_cli_timeout(&["templates", "delete", "--yes", id], org, timeout)
            .await
            .is_ok(),
        "user" => coder_cli_timeout(&["users", "delete", "--yes", id], "", timeout)
            .await
            .is_ok(),
        "org" => coder_cli_timeout(&["organizations", "delete", "--yes", id], "", timeout)
            .await
            .is_ok(),
        _ => false,
    }
}

