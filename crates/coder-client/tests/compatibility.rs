// ── Mutating scenario (prefix `mut_`, single ordered test) ─────────────────
// One ordered scenario so every step's prerequisites exist before the next:
// org -> provisioner key (structured API) + running daemon -> machine identity
// + roles -> template version -> workspace (explicit org/owner/version) ->
// build waited to success -> token minted for the isolation identity. Every
// resource is recorded in the ledger immediately after it is created, keyed by
// its immutable resource ID. Two orgs (A and B) are provisioned so the
// isolation check has real cross-tenant fixtures.

struct OrgFixture {
    org_name: String,
    org_id: String,
    workspace_name: String,
    token_file: String,
}

async fn provision_org_fixture(
    client: &CoderClient,
    deployment: &str,
    suffix: &str,
    label: &str,
) -> OrgFixture {
    let cmd_timeout = std::time::Duration::from_secs(180);
    let org = format!("{}{}-{}", org_prefix(), label, suffix);
    assert_not_default_org(&org);

    // 1. Organization.
    let _ = coder_cli_timeout(&["organizations", "create", &org], "", cmd_timeout).await;
    let orgs = client
        .list_organizations()
        .await
        .expect("list_organizations");
    let org_id = orgs
        .iter()
        .find(|o| o.name == org)
        .map(|o| o.id.clone())
        .unwrap_or_else(|| panic!("org {org} not visible"));
    ledger_record(deployment, &org, "org", &org, &org_id);
    println!("VERIFIED_LIVE org {org} (id={org_id})");

    // 2. Org-scoped provisioner key via the structured API (the pinned server
    //    returns a raw 43-char secret in `{"key": ...}`; the AGPL CLI does not
    //    even expose `provisioner keys create`).
    let key_name = format!("ofci-key-{label}-{suffix}");
    let daemon_key = create_provisioner_key_api(client, &org_id, &key_name)
        .await
        .unwrap_or_else(|e| panic!("provisioner key create failed: {e}"));
    ledger_record(deployment, &org, "provisioner_key", &key_name, &key_name);
    // Persist the one-time daemon secret (0600) so cleanup can re-spawn the
    // daemon to run Terraform deletion jobs.
    write_provisioner_secret(&org_id, &daemon_key);
    let mut daemon = start_provisioner_daemon(&org_id);
    wait_for_provisioner_ready(
        client,
        &org_id,
        &key_name,
        std::time::Duration::from_secs(120),
    )
    .await;

    // 3. Machine identity (service account) in the org.
    let username = format!("ofci-sa-{label}-{suffix}");
    coder_cli_timeout(
        &[
            "users",
            "create",
            "--service-account",
            "--username",
            &username,
            "--org",
            &org,
            "--email",
            &format!("{username}@invalid.local"),
        ],
        "",
        cmd_timeout,
    )
    .await
    .unwrap_or_else(|e| panic!("service account create failed: {}", redact_string(&e)));
    // Resolve the immutable user id for the ledger.
    let users = client.list_users().await.unwrap_or_default();
    let user_id = users
        .iter()
        .find(|u| u.username == username)
        .map(|u| u.id.clone())
        .unwrap_or_default();
    ledger_record(deployment, &org, "user", &username, &user_id);
    println!("VERIFIED_LIVE machine identity created: {username}");

    // 4. Assign org roles directly (service accounts do not inherit
    //    `agents-access`). Org-scoped via CODER_ORGANIZATION.
    coder_cli_timeout(
        &[
            "organizations",
            "members",
            "edit-roles",
            &username,
            "organization-workspace-access",
            "agents-access",
        ],
        &org,
        cmd_timeout,
    )
    .await
    .unwrap_or_else(|e| panic!("org role assign failed: {}", redact_string(&e)));
    println!("VERIFIED_LIVE machine identity roles assigned (workspace-access, agents-access)");

    // 5. Publish a template version into the org with an explicit version name.
    let template_name = format!("{}{}-{}", org_prefix(), "nexus", label);
    let version = format!("ofci-wp00-{suffix}");
    let tmp = tempfile::tempdir().expect("tempdir");
    std::fs::write(tmp.path().join("main.tf"), VALID_MINIMAL_MAIN_TF)
        .expect("write minimal main.tf");
    coder_cli_timeout(
        &[
            "templates",
            "push",
            "--yes",
            "--org",
            &org,
            "--name",
            &version,
            "-d",
            tmp.path().to_str().unwrap(),
            &template_name,
        ],
        "",
        cmd_timeout,
    )
    .await
    .unwrap_or_else(|e| panic!("templates push failed: {}", redact_string(&e)));
    let template_id = client
        .list_templates()
        .await
        .unwrap_or_default()
        .into_iter()
        .find(|t| t.name == template_name)
        .map(|t| t.id)
        .unwrap_or_default();
    ledger_record(deployment, &org, "template", &template_name, &template_id);
    println!("VERIFIED_LIVE published template version {version} for {template_name} in {org}");

    // 6. Workspace with explicit org, owner, and pinned version (no-wait).
    let ws_name = format!("ofci-check-{label}-{suffix}");
    coder_cli_timeout(
        &[
            "create",
            "--yes",
            "--org",
            &org,
            "--template",
            &template_name,
            "--template-version",
            &version,
            "--no-wait",
            &format!("{username}/{ws_name}"),
        ],
        "",
        cmd_timeout,
    )
    .await
    .unwrap_or_else(|e| {
        panic!(
            "workspace create with explicit version failed: {}",
            redact_string(&e)
        )
    });
    // Record the workspace in the ledger IMMEDIATELY after creation, before
    // any polling or validation. A failed build or timeout still leaves the
    // workspace tracked so cleanup can delete it (and its dependency chain).
    // The immutable resource id is not yet resolved, so it is recorded empty
    // and filled in below once the build resolves it (ledger_record updates
    // the same entry).
    ledger_record(
        deployment,
        &org,
        "workspace",
        &format!("{username}/{ws_name}"),
        "",
    );

    // 7. Wait for the workspace build to complete (job succeeded and/or the
    //    workspace running; a provisioner is still running here, so creation is
    //    not left queued).
    let ws_id =
        wait_for_workspace_build_succeeded(client, &ws_name, std::time::Duration::from_secs(300))
            .await;

    // 8. Verify the workspace's exact org/owner/template/version identity.
    verify_workspace_ownership(
        client,
        &ws_name,
        &org_id,
        &username,
        &template_name,
        &version,
    )
    .await;
    println!("VERIFIED_LIVE workspace {username}/{ws_name} org={org} version={version} id={ws_id}");
    ledger_record(
        deployment,
        &org,
        "workspace",
        &format!("{username}/{ws_name}"),
        &ws_id,
    );

    // 9. Mint a session token for the machine identity so the isolation check
    //    can act as this org-local identity. Written to a 0600 file.
    let token_file = mint_identity_token(client, &user_id, &username).await;

    // The provisioner daemon's job (workspace creation) is complete; drop it
    // (kill_on_drop kills the child). Cleanup spawns its own daemons from the
    // stored secret when it needs to run deletion jobs.
    stop_provisioner_daemon(&mut daemon).await;

    OrgFixture {
        org_name: org,
        org_id,
        workspace_name: ws_name,
        token_file,
    }
}

/// Mint an API token for a machine identity via the admin client and write it
/// to a 0600 file, returning the file path. If minting fails, an empty path is
/// returned and the isolation check will fail loudly when the token is absent.
async fn mint_identity_token(client: &CoderClient, user_id: &str, username: &str) -> String {
    use std::os::unix::fs::PermissionsExt;
    if user_id.is_empty() {
        return String::new();
    }
    let name = format!("ofci-iso-{username}");
    let path = std::env::temp_dir().join(format!("ofci-token-{user_id}.secret"));
    match client.create_api_token(user_id, &name).await {
        Ok(api_key) if !api_key.key.is_empty() => {
            std::fs::write(&path, api_key.key).expect("write identity token file");
            std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o600))
                .expect("chmod 0600 identity token");
            path.to_string_lossy().to_string()
        }
        Ok(_) => {
            println!("WARN: identity token for {username} minted empty; isolation may fail");
            String::new()
        }
        Err(e) => {
            println!(
                "WARN: could not mint identity token for {username} ({}); isolation may fail",
                redact_string(&e.to_string())
            );
            String::new()
        }
    }
}

