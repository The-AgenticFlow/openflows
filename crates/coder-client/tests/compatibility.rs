// ── Isolation check (prefix `iso_`, requires fixtures from `mut_`) ─────────
// Proves cross-tenant isolation with explicit org IDs, known workspace
// fixtures, and authenticated denials only. Positive controls first: each
// identity proves it can read ITS OWN org's models and list ITS OWN workspace
// fixture, and create a chat in its own org. Then negative controls: each
// identity must be denied access to the other org's workspace by its exact
// name, and denied chat access in the other org. A 401 is NOT treated as proof
// of isolation (it could indicate a broken credential rather than a denied
// access). Missing mandatory fixtures is a hard failure, not a silent pass.

#[tokio::test]
#[ignore = "requires OPENFLOWS_CODER_MUTATE=1, a licensed deployment, and two machine identities"]
async fn iso_cross_tenant() {
    require_mutate();
    require_live_client();
    let url = coder_url().expect("CODER_URL");

    // Mandatory fixtures: two org names, two workspace fixture names, two token
    // files. If any are missing, the isolation contract cannot be verified, so
    // this is a hard failure (not a misleading green NOT_VERIFIED return).
    let (org_a, org_b) = match (std::env::var(ENV_ORG_A).ok(), std::env::var(ENV_ORG_B).ok()) {
        (Some(a), Some(b)) if !a.is_empty() && !b.is_empty() => (a, b),
        _ => panic!(
            "MANDATORY isolation fixtures missing: OPENFLOWS_CODER_ORG_A / \
             OPENFLOWS_CODER_ORG_B must name the orgs created by --mutating. \
             Run the mutating scenario first, then re-run with the manifest sourced."
        ),
    };
    let (ws_a, ws_b) = match (std::env::var(ENV_WS_A).ok(), std::env::var(ENV_WS_B).ok()) {
        (Some(a), Some(b)) if !a.is_empty() && !b.is_empty() => (a, b),
        _ => panic!(
            "MANDATORY isolation fixtures missing: OPENFLOWS_CODER_WS_A / \
             OPENFLOWS_CODER_WS_B must name the workspace fixtures created by --mutating."
        ),
    };
    let (ta, tb) = match (
        std::env::var(ENV_TOKEN_A_FILE).ok(),
        std::env::var(ENV_TOKEN_B_FILE).ok(),
    ) {
        (Some(a), Some(b)) => (
            std::fs::read_to_string(&a)
                .expect("token A file")
                .trim()
                .to_string(),
            std::fs::read_to_string(&b)
                .expect("token B file")
                .trim()
                .to_string(),
        ),
        _ => panic!(
            "MANDATORY isolation fixtures missing: OPENFLOWS_CODER_TOKEN_A_FILE / \
             OPENFLOWS_CODER_TOKEN_B_FILE must point to tokens for the org A and \
             org B machine identities."
        ),
    };
    let ca = CoderClient::new(&url, &ta);
    let cb = CoderClient::new(&url, &tb);

    // Resolve each org's ID with the token that owns it.
    let org_id_a = org_id_for(&ca, &org_a).await;
    let org_id_b = org_id_for(&cb, &org_b).await;

    // ── Positive controls ──────────────────────────────────────────────
    let models_a = read_models_expect(&ca, &org_id_a, "A reads own org A models").await;
    let models_b = read_models_expect(&cb, &org_id_b, "B reads own org B models").await;
    println!(
        "positive control: A read {} models in {org_a}, B read {} models in {org_b}",
        models_a, models_b
    );

    // Each identity lists and sees ITS OWN workspace fixture. A request failure
    // here is a hard error, never a pass.
    assert!(
        matches!(
            workspace_access(&ca, &ws_a)
                .await
                .unwrap_or_else(|e| panic!("positive control A on {ws_a}: {e}")),
            WorkspaceAccess::Visible
        ),
        "positive control failed: A cannot see its own workspace {ws_a}"
    );
    assert!(
        matches!(
            workspace_access(&cb, &ws_b)
                .await
                .unwrap_or_else(|e| panic!("positive control B on {ws_b}: {e}")),
            WorkspaceAccess::Visible
        ),
        "positive control failed: B cannot see its own workspace {ws_b}"
    );
    println!("positive control: A sees {ws_a}, B sees {ws_b}");

    assert!(
        chat_access_ok(&ca, &org_id_a).await,
        "positive control failed: A cannot create a chat in its own org"
    );
    assert!(
        chat_access_ok(&cb, &org_id_b).await,
        "positive control failed: B cannot create a chat in its own org"
    );
    println!("positive control: A and B can each create a chat in their own org");

    // ── Negative controls (authenticated denials / invisible resources) ─
    // Workspaces: A must not see B's fixture, and vice versa. Only a valid
    // outcome (empty 200 or explicit 403/404) establishes isolation; a request
    // failure or unexpected status fails the check instead of passing it.
    let a_ws_on_b = workspace_access(&ca, &ws_b)
        .await
        .unwrap_or_else(|e| panic!("A->B workspace check failed (unexpected): {e}"));
    assert!(
        matches!(a_ws_on_b, WorkspaceAccess::NotVisible),
        "VERIFIED_LIVE FAILURE: A can see B's workspace {ws_b} — cross-tenant leak"
    );
    let b_ws_on_a = workspace_access(&cb, &ws_a)
        .await
        .unwrap_or_else(|e| panic!("B->A workspace check failed (unexpected): {e}"));
    assert!(
        matches!(b_ws_on_a, WorkspaceAccess::NotVisible),
        "VERIFIED_LIVE FAILURE: B can see A's workspace {ws_a} — cross-tenant leak"
    );
    println!("negative control: cross-tenant workspace access denied in both directions");

    // Models: A must not read B's org models, and vice versa. A 401 or request
    // failure is NOT accepted as proof of isolation.
    let a_models_on_b = read_models_status(&ca, &org_id_b).await;
    let b_models_on_a = read_models_status(&cb, &org_id_a).await;
    assert!(
        is_denied(a_models_on_b) && is_denied(b_models_on_a),
        "VERIFIED_LIVE FAILURE: model cross-tenant access not denied (A->B={a_models_on_b}, B->A={b_models_on_a})"
    );
    println!("negative control: cross-tenant model access denied in both directions");

    let a_chat_on_b = chat_access_status(&ca, &org_id_b).await;
    let b_chat_on_a = chat_access_status(&cb, &org_id_a).await;
    assert!(
        is_denied(a_chat_on_b) && is_denied(b_chat_on_a),
        "VERIFIED_LIVE FAILURE: chat cross-tenant access not denied (A->B={a_chat_on_b}, B->A={b_chat_on_a})"
    );
    println!("negative control: cross-tenant chat access denied in both directions");

    println!(
        "VERIFIED_LIVE cross-tenant isolation holds in both directions (models, workspaces, chats)"
    );
}

fn is_denied(status: u16) -> bool {
    // Authenticated denial only; 401 (unauthenticated) does not prove isolation.
    status == 403 || status == 404
}

/// Resolve an org ID by name for the caller's token; panic if not visible.
async fn org_id_for(client: &CoderClient, name: &str) -> String {
    let orgs = client
        .list_organizations()
        .await
        .unwrap_or_else(|e| panic!("list orgs for {name}: {e}"));
    orgs.iter()
        .find(|o| o.name == name)
        .map(|o| o.id.clone())
        .unwrap_or_else(|| panic!("org {name} not visible to the calling identity"))
}

/// The outcome of a caller's attempt to read a workspace by name.
#[derive(Debug, Clone, PartialEq, Eq)]
enum WorkspaceAccess {
    /// The caller successfully listed and saw the workspace (200 + present).
    Visible,
    /// A valid response established the workspace is not visible: an empty 200
    /// (correct isolation) or an explicit authorization denial (403/404).
    NotVisible,
}

/// Pure decision function mapping an HTTP status and workspace-presence to an
/// isolation outcome. Only valid responses establish isolation: an explicit
/// authenticated denial (403/404) or a valid 200. Any other status (5xx, 401)
/// or a zero status (network failure) is an error and must NOT be treated as
/// proof of invisibility.
fn classify_workspace_access(status: u16, present: bool) -> Result<WorkspaceAccess, String> {
    if status == 403 || status == 404 {
        return Ok(WorkspaceAccess::NotVisible);
    }
    if status != 200 {
        return Err(format!("list workspaces returned HTTP {status}"));
    }
    if present {
        Ok(WorkspaceAccess::Visible)
    } else {
        // A valid empty 200 (only the summary row) is correct isolation.
        Ok(WorkspaceAccess::NotVisible)
    }
}

/// Classify a valid 200 `WorkspacesResponse` body for workspace isolation.
///
/// The body MUST carry a `workspaces` array (Coder returns
/// `{"workspaces": [...], "count": n}`, possibly empty). A malformed body with
/// no `workspaces` field or a non-array value (e.g. `{}` or
/// `{"workspaces": null}`) is an error and must NOT be treated as "not
/// visible" — otherwise a garbled response could satisfy the negative
/// isolation check.
fn classify_workspace_body(body: &Value, ws_name: &str) -> Result<WorkspaceAccess, String> {
    let workspaces = body
        .get("workspaces")
        .and_then(Value::as_array)
        .ok_or_else(|| {
            "workspace response is malformed: missing a `workspaces` array".to_string()
        })?;
    let present = workspaces
        .iter()
        .any(|w| w.get("name").and_then(Value::as_str) == Some(ws_name));
    if present {
        Ok(WorkspaceAccess::Visible)
    } else {
        Ok(WorkspaceAccess::NotVisible)
    }
}

/// Probe whether the caller can list the workspace named `ws_name`.
///
/// Only valid responses establish isolation. A request failure (timeout,
/// network error), an unexpected HTTP status (5xx), an unauthenticated 401, or
/// a malformed body is returned as `Err` and must NOT be treated as proof of
/// invisibility — that could flag a secure deployment as insecure or let a
/// broken credential pass.
async fn workspace_access(client: &CoderClient, ws_name: &str) -> Result<WorkspaceAccess, String> {
    let resp = http_client()
        .get(format!(
            "{}/api/v2/workspaces?q=name:{}",
            client.base_url(),
            ws_name
        ))
        .header("Authorization", format!("Bearer {}", client.token()))
        .send()
        .await
        .map_err(|e| format!("list workspaces {ws_name} request failed: {e}"))?;
    let status = resp.status().as_u16();
    if status == 403 || status == 404 {
        return Ok(WorkspaceAccess::NotVisible);
    }
    if status != 200 {
        return Err(format!("list workspaces {ws_name} returned HTTP {status}"));
    }
    let body: Value = resp
        .json()
        .await
        .map_err(|e| format!("list workspaces {ws_name} body invalid: {e}"))?;
    classify_workspace_body(&body, ws_name)
}

