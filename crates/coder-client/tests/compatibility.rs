/// Regex fragments for token-like strings that must never reach logs.
fn token_patterns() -> &'static [&'static str] {
    &[
        r"(?i)bearer\s+[A-Za-z0-9._~+/=-]{8,}",
        r"(?i)(coder|ghp|gho|ghs|github_pat|glpat)[_-][A-Za-z0-9_]{16,}",
        r"(?i)(token|secret|password|apikey|access_key)\s*[=:]\s*[A-Za-z0-9._~+/=-]{8,}",
        r"[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{20,}",
        r"(?i)CODER_SESSION_TOKEN\s*[=:]\s*\S+",
    ]
}

/// Scrub token-like patterns from arbitrary text (JSON or plaintext).
fn redact_string(s: &str) -> String {
    let mut out = s.to_string();
    for pat in token_patterns() {
        if let Ok(re) = regex::Regex::new(pat) {
            out = re.replace_all(&out, "<REDACTED>").to_string();
        }
    }
    out
}

/// Recursively redact a serde value by field name, for structured bodies.
fn redact(v: &Value) -> Value {
    match v {
        Value::Object(map) => {
            let mut out = serde_json::Map::new();
            for (k, val) in map {
                let key_lc = k.to_ascii_lowercase();
                if key_lc.contains("token")
                    || key_lc.contains("secret")
                    || key_lc.contains("password")
                    || key_lc.contains("key")
                    || key_lc.contains("access_token")
                {
                    out.insert(k.clone(), Value::String("<REDACTED>".into()));
                } else {
                    out.insert(k.clone(), redact(val));
                }
            }
            Value::Object(out)
        }
        Value::Array(arr) => Value::Array(arr.iter().map(redact).collect()),
        other => other.clone(),
    }
}

/// Resolve the operator session token without ever echoing it.
fn resolve_token() -> Option<String> {
    if let Ok(t) = std::env::var(ENV_CODER_TOKEN) {
        if !t.trim().is_empty() {
            return Some(t);
        }
    }
    if let Ok(path) = std::env::var(ENV_CODER_TOKEN_FILE) {
        if let Ok(t) = std::fs::read_to_string(&path) {
            let t = t.trim().to_string();
            if !t.is_empty() {
                return Some(t);
            }
        }
    }
    None
}

fn coder_url() -> Option<String> {
    let url = std::env::var(ENV_CODER_URL).ok()?;
    if url.trim().is_empty() {
        None
    } else {
        Some(url.trim_end_matches('/').to_string())
    }
}

/// An HTTP client with a per-request timeout so one hung request cannot exceed
/// an enclosing polling deadline.
fn http_client() -> reqwest::Client {
    reqwest::Client::builder()
        .timeout(std::time::Duration::from_secs(15))
        .build()
        .unwrap_or_default()
}

/// Fail with a `NOT_VERIFIED` marker when the live environment is absent.
fn require_live_client() -> CoderClient {
    let url = coder_url().expect(
        "NOT_VERIFIED: CODER_URL is not set; no licensed Coder deployment was configured. \
         This check cannot run and is reported NOT_VERIFIED, not VERIFIED_LIVE.",
    );
    let token = resolve_token().expect(
        "NOT_VERIFIED: neither CODER_SESSION_TOKEN nor CODER_SESSION_TOKEN_FILE is set. \
         This check cannot run and is reported NOT_VERIFIED, not VERIFIED_LIVE.",
    );
    CoderClient::new(&url, &token)
}

fn mutate_enabled() -> bool {
    std::env::var(ENV_MUTATE).map(|v| v == "1").unwrap_or(false)
}

fn require_mutate() {
    assert!(
        mutate_enabled(),
        "NOT_VERIFIED: mutating checks require OPENFLOWS_CODER_MUTATE=1. \
         Refusing to create resources without explicit opt-in."
    );
}

fn org_prefix() -> String {
    std::env::var(ENV_ORG_PREFIX).unwrap_or_else(|_| "ofci-".to_string())
}

fn run_suffix() -> String {
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    format!("{:x}", nanos % 0xFFFF_FFFF)
}

fn assert_not_default_org(org: &str) {
    assert!(
        !org.eq_ignore_ascii_case("coder") && !org.is_empty(),
        "Refusing to mutate the default organization (org={org}). \
         Mutating checks must target the isolated test org prefix."
    );
}

/// Run a `coder` CLI subcommand synchronously. Never passes the token on argv.
/// `org` scopes the command via CODER_ORGANIZATION when non-empty.
fn coder_cli(args: &[&str], org: &str) -> Result<String, String> {
    let url = coder_url().ok_or("CODER_URL not set")?;
    let token = resolve_token().ok_or("session token not set")?;
    let mut cmd = Command::new("coder");
    cmd.args(args)
        .env("CODER_URL", &url)
        .env("CODER_SESSION_TOKEN", &token)
        .env("CODER_TOKEN", &token);
    if !org.is_empty() {
        cmd.env("CODER_ORGANIZATION", org);
    }
    let out = cmd
        .output()
        .map_err(|e| format!("failed to spawn `coder`: {e}"))?;
    let stdout = String::from_utf8_lossy(&out.stdout).to_string();
    let stderr = String::from_utf8_lossy(&out.stderr).to_string();
    if !out.status.success() {
        return Err(format!(
            "`coder {}` exited {}: stderr={}",
            args.join(" "),
            out.status,
            redact_string(&stderr)
        ));
    }
    Ok(stdout)
}

/// Run a `coder` CLI subcommand under a wall-clock timeout (async).
///
/// `kill_on_drop(true)` is required so that when the enclosing `timeout`
/// future is dropped the child process is killed and reaped instead of being
/// orphaned and left creating resources after the scenario has moved on.
async fn coder_cli_timeout(
    args: &[&str],
    org: &str,
    timeout: std::time::Duration,
) -> Result<String, String> {
    let url = coder_url().ok_or("CODER_URL not set")?;
    let token = resolve_token().ok_or("session token not set")?;
    let mut cmd = tokio::process::Command::new("coder");
    cmd.args(args)
        .env("CODER_URL", &url)
        .env("CODER_SESSION_TOKEN", &token)
        .env("CODER_TOKEN", &token)
        .kill_on_drop(true);
    if !org.is_empty() {
        cmd.env("CODER_ORGANIZATION", org);
    }
    let out = tokio::time::timeout(timeout, cmd.output())
        .await
        .map_err(|_| format!("`coder {}` timed out after {timeout:?}", args.join(" ")))?
        .map_err(|e| format!("failed to spawn `coder`: {e}"))?;
    let stdout = String::from_utf8_lossy(&out.stdout).to_string();
    let stderr = String::from_utf8_lossy(&out.stderr).to_string();
    if !out.status.success() {
        return Err(format!(
            "`coder {}` exited {}: stderr={}",
            args.join(" "),
            out.status,
            redact_string(&stderr)
        ));
    }
    Ok(stdout)
}

// ── Persistent, atomically-written resource ledger ─────────────────────────
// Every entry records the deployment URL, organization, and the resource's
// immutable ID so cleanup can validate that a recorded resource belongs to
// THIS deployment and org before deleting it, and so distinct resources with
// the same human name in different orgs never collide. Identity is
// `(deployment_url, org, kind, resource_id)`. The read-modify-write cycle is
// serialized with a cross-process lock file so two harness processes cannot
// clobber one another's ledger. Entries are appended/updated under that lock
// and the file is rewritten atomically. Status transitions are `created` ->
// `delete_failed` | `deleted`; entries that fail to delete are retained.

#[derive(Serialize, Deserialize, Clone)]
struct LedgerEntry {
    deployment_url: String,
    org: String,
    kind: String, // org | template | provisioner_key | user | workspace
    /// Human-facing name/identifier (e.g. template name, `owner/ws`).
    id: String,
    /// Immutable server-assigned resource ID (template_id, workspace_id, ...).
    /// Empty only when the ID could not be resolved before recording.
    resource_id: String,
    status: String, // created | deleted | delete_failed
}

#[derive(Serialize, Deserialize, Default)]
struct Ledger {
    entries: Vec<LedgerEntry>,
}

static LEDGER_LOCK: Mutex<()> = Mutex::new(());

fn ledger_path() -> std::path::PathBuf {
    if let Ok(p) = std::env::var(ENV_LEDGER_FILE) {
        return std::path::PathBuf::from(p);
    }
    std::env::temp_dir().join("ofci-ledger.json")
}

fn load_ledger_locked() -> Ledger {
    let path = ledger_path();
    if let Ok(text) = std::fs::read_to_string(&path) {
        if let Ok(ledger) = serde_json::from_str::<Ledger>(&text) {
            return ledger;
        }
    }
    Ledger::default()
}

fn persist_ledger(ledger: &Ledger) {
    let path = ledger_path();
    let text = serde_json::to_string_pretty(ledger).expect("serialize ledger");
    // Atomic write: write temp then rename so a crash never leaves a torn file.
    let tmp = path.with_extension("json.tmp");
    std::fs::write(&tmp, text).expect("write ledger temp");
    std::fs::rename(&tmp, &path).expect("atomic ledger replace");
    println!("ledger written to {}", path.display());
}

/// Acquire a cross-process exclusive lock on the ledger and run `f`, releasing
/// the lock afterwards. Guards the read-modify-write cycle against a second
/// harness process; the in-process mutex handles threads in the same process.
fn with_ledger_lock<T>(f: impl FnOnce() -> T) -> T {
    let _guard = LEDGER_LOCK.lock().expect("ledger lock poisoned");
    let lock_path = ledger_path().with_extension("lock");
    let deadline = std::time::Instant::now() + std::time::Duration::from_secs(30);
    let lock_file = loop {
        match std::fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&lock_path)
        {
            Ok(f) => break f,
            Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => {
                if std::time::Instant::now() >= deadline {
                    panic!("timed out acquiring ledger lock {}", lock_path.display());
                }
                std::thread::sleep(std::time::Duration::from_millis(100));
            }
            Err(e) => panic!("failed to create ledger lock {}: {e}", lock_path.display()),
        }
    };
    let result = std::panic::catch_unwind(std::panic::AssertUnwindSafe(f));
    drop(lock_file);
    let _ = std::fs::remove_file(&lock_path);
    match result {
        Ok(v) => v,
        Err(p) => std::panic::resume_unwind(p),
    }
}

/// The composite identity key for a ledger entry.
fn ledger_identity(deployment: &str, org: &str, kind: &str, resource_id: &str) -> String {
    format!("{deployment}\u{1f}::{org}\u{1f}::{kind}\u{1f}::{resource_id}")
}

/// Record a created resource immediately. `org` is the org it belongs to;
/// `resource_id` is the immutable server-assigned ID when known (empty
/// otherwise). Panics on write failure so a lost record (and thus an unsafe
/// cleanup) is never silent.
///
/// Identity is `(deployment, org, kind, resource_id)`. When a resource is
/// recorded with an empty `resource_id` (its server ID not yet resolved, e.g. a
/// workspace recorded immediately after creation) and later re-recorded with
/// the real ID, the same entry is updated rather than duplicated: matching
/// falls back to the human `id` while either side has an empty `resource_id`.
fn ledger_record(deployment_url: &str, org: &str, kind: &str, id: &str, resource_id: &str) {
    with_ledger_lock(|| {
        let mut ledger = load_ledger_locked();
        let key = ledger_identity(deployment_url, org, kind, resource_id);
        let existing = ledger.entries.iter_mut().find(|e| {
            let by_resource =
                ledger_identity(&e.deployment_url, &e.org, &e.kind, &e.resource_id) == key;
            let by_human_id = (resource_id.is_empty() || e.resource_id.is_empty())
                && e.deployment_url == deployment_url
                && e.org == org
                && e.kind == kind
                && e.id == id;
            by_resource || by_human_id
        });
        if let Some(e) = existing {
            e.status = "created".to_string();
            e.deployment_url = deployment_url.to_string();
            e.org = org.to_string();
            e.id = id.to_string();
            if !resource_id.is_empty() {
                e.resource_id = resource_id.to_string();
            }
        } else {
            ledger.entries.push(LedgerEntry {
                deployment_url: deployment_url.to_string(),
                org: org.to_string(),
                kind: kind.to_string(),
                id: id.to_string(),
                resource_id: resource_id.to_string(),
                status: "created".to_string(),
            });
        }
        persist_ledger(&ledger);
    });
}

/// Mark a ledger entry's deletion outcome and retain it unless fully deleted.
fn ledger_delete_result(kind: &str, id: &str, resource_id: &str, org: &str, ok: bool) {
    with_ledger_lock(|| {
        let mut ledger = load_ledger_locked();
        for e in ledger.entries.iter_mut() {
            let id_matches = if resource_id.is_empty() {
                e.id == id
            } else {
                e.resource_id == resource_id
            };
            if e.kind == kind && e.org == org && id_matches {
                e.status = if ok { "deleted" } else { "delete_failed" }.to_string();
            }
        }
        // Retain entries that failed; drop only fully-deleted ones.
        ledger.entries.retain(|e| e.status != "deleted");
        persist_ledger(&ledger);
    });
}

// ── Provisioner key parsing ────────────────────────────────────────────────
//
// The pinned Coder (`v2.37.3`) generates a raw 43-character alphanumeric
// secret (`provisionerkey.New` -> `apikey.GenerateSecret(43)` ->
// `cryptorand.String(43)` using the default `0-9A-Za-z` charset). It does NOT
// carry a `coder_` prefix. `coder provisioner keys create` is not even exposed
// by the AGPL CLI; the structured API response is the canonical source:
// `POST /api/v2/organizations/{org}/provisionerkeys` -> `{"key": "<secret>"}`.
//
// The parser accepts either that structured JSON `key` field or a standalone
// 43-character line (as a real CLI would print it), and validates the shape.

/// True when `s` is a well-formed raw provisioner secret: exactly 43 chars,
/// all in `0-9A-Za-z`.
fn is_provisioner_secret(s: &str) -> bool {
    if s.len() != PROVISIONER_KEY_SECRET_LEN {
        return false;
    }
    s.chars().all(|c| c.is_ascii_alphanumeric())
}

/// Extract the one-time provisioner daemon secret from command output or a
/// structured API response, without ever logging it. Never echoes the token.
fn extract_daemon_key(key_out: &str) -> Option<String> {
    // Structured API response: `{"key": "<43-char secret>"}`.
    if let Ok(v) = serde_json::from_str::<Value>(key_out) {
        if let Some(k) = v.get("key").and_then(Value::as_str) {
            if is_provisioner_secret(k) {
                return Some(k.to_string());
            }
        }
    }
    // Plaintext: a standalone line that is exactly the raw 43-char secret.
    let re = regex::Regex::new(r"(?m)^([A-Za-z0-9]{43})\s*$").ok()?;
    for cap in re.captures_iter(key_out) {
        if let Some(m) = cap.get(1) {
            let cand = m.as_str();
            if is_provisioner_secret(cand) {
                return Some(cand.to_string());
            }
        }
    }
    None
}

/// Create a provisioner key via the structured REST API (the canonical,
/// version-agnostic route) and return the raw daemon secret.
async fn create_provisioner_key_api(
    client: &CoderClient,
    org_id: &str,
    name: &str,
) -> Result<String, String> {
    let resp = http_client()
        .post(format!(
            "{}/api/v2/organizations/{}/provisionerkeys",
            client.base_url(),
            org_id
        ))
        .header("Authorization", format!("Bearer {}", client.token()))
        .json(&serde_json::json!({ "name": name }))
        .send()
        .await
        .map_err(|e| format!("provisioner key create request failed: {e}"))?;
    let status = resp.status().as_u16();
    let body: Value = resp.json().await.unwrap_or(Value::Null);
    if status != 201 {
        return Err(format!(
            "provisioner key create returned {status}: {}",
            redact(&body)
        ));
    }
    let key = body
        .get("key")
        .and_then(Value::as_str)
        .ok_or_else(|| format!("provisioner key response missing `key`: {}", redact(&body)))?;
    if !is_provisioner_secret(key) {
        return Err(format!(
            "provisioner key response `key` is not a valid {PROVISIONER_KEY_SECRET_LEN}-char secret"
        ));
    }
    Ok(key.to_string())
}

/// Delete a provisioner key via REST (the AGPL CLI exposes no delete command).
async fn delete_provisioner_key_api(
    client: &CoderClient,
    org_id: &str,
    name: &str,
) -> Result<(), String> {
    let resp = http_client()
        .delete(format!(
            "{}/api/v2/organizations/{}/provisionerkeys/{}",
            client.base_url(),
            org_id,
            name
        ))
        .header("Authorization", format!("Bearer {}", client.token()))
        .send()
        .await
        .map_err(|e| format!("provisioner key delete request failed: {e}"))?;
    if resp.status().as_u16() == 204 || resp.status().is_success() {
        Ok(())
    } else {
        Err(format!("provisioner key delete returned {}", resp.status()))
    }
}

// ── Provisioner daemon readiness ───────────────────────────────────────────
//
// The pinned server registers the daemon listing at
// `/api/v2/organizations/{id}/provisionerdaemons` (NOT `/provisioners`), and a
// nonempty response alone does not establish that the intended daemon is
// connected. We verify identity (`key_name` matches the key we created) and
// usability (`status` is `idle` or `busy`, never `offline`).

/// Returns `(ready, reason)`. `ready` is true only when a provisioner daemon
/// authenticated with `key_name` reports an online status.
async fn provisioner_daemons_ready(
    client: &CoderClient,
    org_id: &str,
    key_name: &str,
) -> (bool, String) {
    let resp = http_client()
        .get(format!(
            "{}/api/v2/organizations/{}/provisionerdaemons",
            client.base_url(),
            org_id
        ))
        .header("Authorization", format!("Bearer {}", client.token()))
        .send()
        .await;
    let body: Value = match resp {
        Ok(r) if r.status().is_success() => r.json().await.unwrap_or(Value::Null),
        Ok(r) => return (false, format!("provisionerdaemons HTTP {}", r.status())),
        Err(e) => return (false, format!("provisionerdaemons request failed: {e}")),
    };
    let daemons = body.as_array().cloned().unwrap_or_default();
    if daemons.is_empty() {
        return (false, "no provisioner daemons reported".to_string());
    }
    for d in &daemons {
        let key_name_field = d.get("key_name").and_then(Value::as_str).unwrap_or("");
        if key_name_field == key_name {
            let status = d.get("status").and_then(Value::as_str).unwrap_or("unknown");
            let daemon_name = d.get("name").and_then(Value::as_str).unwrap_or("<unnamed>");
            match status {
                "idle" | "busy" => return (true, format!("daemon {daemon_name} is {status}")),
                _ => {
                    return (
                        false,
                        format!("daemon {daemon_name} for key {key_name} is {status}"),
                    )
                }
            }
        }
    }
    (
        false,
        format!("no daemon for key {key_name} found in the listing"),
    )
}

async fn wait_for_provisioner_ready(
    client: &CoderClient,
    org_id: &str,
    key_name: &str,
    timeout: std::time::Duration,
) {
    let deadline = std::time::Instant::now() + timeout;
    loop {
        let (ready, reason) = provisioner_daemons_ready(client, org_id, key_name).await;
        if ready {
            println!("VERIFIED_LIVE provisioner ready for org {org_id}: {reason}");
            return;
        }
        if std::time::Instant::now() >= deadline {
            panic!(
                "provisioner for org {org_id} not ready within {timeout:?} ({reason}); \
                 template import cannot be exercised"
            );
        }
        tokio::time::sleep(std::time::Duration::from_secs(2)).await;
    }
}

/// Path to the 0600 file holding a provisioner daemon's one-time secret for an
/// org, so cleanup can spin the daemon back up to run Terraform deletion jobs.
fn provisioner_secret_path(org_id: &str) -> std::path::PathBuf {
    std::env::temp_dir().join(format!("ofci-daemon-key-{org_id}.secret"))
}

fn write_provisioner_secret(org_id: &str, secret: &str) -> std::path::PathBuf {
    use std::os::unix::fs::PermissionsExt;
    let path = provisioner_secret_path(org_id);
    std::fs::write(&path, secret).expect("write provisioner daemon secret file");
    std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o600))
        .expect("chmod 0600 provisioner daemon secret");
    path
}

fn read_provisioner_secret(org_id: &str) -> Option<String> {
    std::fs::read_to_string(provisioner_secret_path(org_id))
        .ok()
        .map(|s| s.trim().to_string())
        .filter(|s| !s.is_empty())
}

fn start_provisioner_daemon(org_id: &str) -> tokio::process::Child {
    let url = coder_url().expect("CODER_URL");
    let secret = read_provisioner_secret(org_id)
        .unwrap_or_else(|| panic!("no stored provisioner daemon secret for org {org_id}"));
    let mut cmd = tokio::process::Command::new("coder");
    cmd.args(["provisionerd", "start", "--org", org_id])
        .env("CODER_URL", &url)
        .env("CODER_PROVISIONER_DAEMON_KEY", &secret)
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .kill_on_drop(true);
    cmd.spawn().expect("spawn provisionerd")
}

async fn stop_provisioner_daemon(daemon: &mut tokio::process::Child) {
    let _ = daemon.kill().await;
    let _ = daemon.wait().await;
}

// ── Workspace lookup + verification ────────────────────────────────────────
//
// The workspace list endpoint filters by the caller's visibility and uses the
// `q` search parameter, so we resolve a workspace by exact name, then assert
// the exact identity fields (organization, owner, template, build version).

/// Find a workspace object in a `WorkspacesResponse` body by exact name.
/// Returns `None` when absent (empty 200 is a valid, correct outcome).
fn find_workspace_in_response(body: &Value, name: &str) -> Option<Value> {
    body.get("workspaces")
        .and_then(Value::as_array)
        .and_then(|arr| {
            arr.iter()
                .find(|w| w.get("name").and_then(Value::as_str) == Some(name))
                .cloned()
        })
}

/// Validate that a workspace JSON object carries the exact expected identity.
/// Returns `Ok(workspace_id)` when every field matches, otherwise `Err` naming
/// the first mismatched field.
///
/// Build semantics follow the pinned API: `latest_build.status` is a
/// `WorkspaceStatus` (a successful *start* reports `running`, never
/// `succeeded`), while `latest_build.job.status` is a `ProvisionerJobStatus`
/// that reports `succeeded` when the provisioning job finishes. Both must hold.
fn validate_workspace_identity(
    ws: &Value,
    expected_org_id: &str,
    expected_owner: &str,
    expected_template: &str,
    expected_version: &str,
    expected_workspace_status: &str,
) -> Result<String, String> {
    let id = ws
        .get("id")
        .and_then(Value::as_str)
        .unwrap_or("")
        .to_string();
    let org = ws
        .get("organization_id")
        .and_then(Value::as_str)
        .unwrap_or("");
    if org != expected_org_id {
        return Err(format!(
            "organization mismatch: got {org}, expected {expected_org_id}"
        ));
    }
    let owner = ws.get("owner_name").and_then(Value::as_str).unwrap_or("");
    if owner != expected_owner {
        return Err(format!(
            "owner mismatch: got {owner}, expected {expected_owner}"
        ));
    }
    let template = ws
        .get("template_name")
        .and_then(Value::as_str)
        .unwrap_or("");
    if template != expected_template {
        return Err(format!(
            "template mismatch: got {template}, expected {expected_template}"
        ));
    }
    let build = ws.get("latest_build").and_then(Value::as_object);
    let version = build
        .and_then(|b| b.get("template_version_name"))
        .and_then(Value::as_str)
        .unwrap_or("");
    if version != expected_version {
        return Err(format!(
            "template version mismatch: got {version}, expected {expected_version}"
        ));
    }
    // `latest_build.status` is a WorkspaceStatus: a successful start is
    // `running`, never `succeeded`.
    let workspace_status = build
        .and_then(|b| b.get("status"))
        .and_then(Value::as_str)
        .unwrap_or("");
    if workspace_status != expected_workspace_status {
        return Err(format!(
            "workspace status mismatch: got {workspace_status}, expected {expected_workspace_status}"
        ));
    }
    // `latest_build.job.status` is the ProvisionerJobStatus; `succeeded` means
    // the provisioning job (the workspace build) completed.
    let job_status = build
        .and_then(|b| b.get("job"))
        .and_then(|j| j.get("status"))
        .and_then(Value::as_str)
        .unwrap_or("");
    if job_status != "succeeded" {
        return Err(format!(
            "provisioner job status mismatch: got {job_status}, expected succeeded"
        ));
    }
    Ok(id)
}

async fn fetch_workspace_by_name(client: &CoderClient, ws_name: &str) -> Result<Value, String> {
    let resp = http_client()
        .get(format!(
            "{}/api/v2/workspaces?q=name:{}",
            client.base_url(),
            ws_name
        ))
        .header("Authorization", format!("Bearer {}", client.token()))
        .send()
        .await
        .map_err(|e| format!("list workspaces request failed: {e}"))?;
    if !resp.status().is_success() {
        return Err(format!("list workspaces returned {}", resp.status()));
    }
    resp.json::<Value>()
        .await
        .map_err(|e| format!("list workspaces body invalid: {e}"))
}

/// Resolve the workspace by name and validate its exact identity. Returns the
/// workspace ID on success.
async fn verify_workspace_ownership(
    client: &CoderClient,
    ws_name: &str,
    org_id: &str,
    owner: &str,
    template: &str,
    version: &str,
) -> String {
    let body = fetch_workspace_by_name(client, ws_name)
        .await
        .unwrap_or_else(|e| panic!("verify workspace {ws_name}: {e}"));
    let ws = find_workspace_in_response(&body, ws_name)
        .unwrap_or_else(|| panic!("workspace {ws_name} not found in list response"));
    validate_workspace_identity(&ws, org_id, owner, template, version, "running")
        .unwrap_or_else(|e| panic!("workspace {ws_name} identity invalid: {e}"))
}

/// Wait for a workspace's latest build's provisioning job to reach a terminal
/// `succeeded` state, or fail. This is required because the scenario creates
/// workspaces with `--no-wait`; workspace lifecycle work (and the later
/// Terraform deletion job) needs a provisioner to complete.
///
/// Semantics follow the pinned API: `latest_build.job.status`
/// (`ProvisionerJobStatus`) is `succeeded` when the provisioning job finishes;
/// `latest_build.status` (`WorkspaceStatus`) reports `running` for a successful
/// start and never `succeeded`. We accept either the job reaching `succeeded`
/// or the workspace reaching `running`.
async fn wait_for_workspace_build_succeeded(
    client: &CoderClient,
    ws_name: &str,
    timeout: std::time::Duration,
) -> String {
    let deadline = std::time::Instant::now() + timeout;
    loop {
        let body = match fetch_workspace_by_name(client, ws_name).await {
            Ok(b) => b,
            Err(_) => {
                if std::time::Instant::now() >= deadline {
                    panic!("workspace {ws_name}: list failed before build succeeded within {timeout:?}");
                }
                tokio::time::sleep(std::time::Duration::from_secs(3)).await;
                continue;
            }
        };
        if let Some(ws) = find_workspace_in_response(&body, ws_name) {
            let id = ws
                .get("id")
                .and_then(Value::as_str)
                .unwrap_or("")
                .to_string();
            let ws_status = ws
                .get("latest_build")
                .and_then(|b| b.get("status"))
                .and_then(Value::as_str)
                .unwrap_or("")
                .to_string();
            let job_status = ws
                .get("latest_build")
                .and_then(|b| b.get("job"))
                .and_then(|j| j.get("status"))
                .and_then(Value::as_str)
                .unwrap_or("")
                .to_string();
            // A successful start: job succeeded, and/or the workspace is running.
            if job_status == "succeeded" || ws_status == "running" {
                return id;
            }
            // Terminal failures.
            if matches!(
                ws_status.as_str(),
                "failed" | "canceled" | "canceling" | "deleted"
            ) || matches!(job_status.as_str(), "failed" | "canceled" | "canceling")
            {
                panic!("workspace {ws_name} build ended (status={ws_status}, job={job_status})");
            }
        }
        if std::time::Instant::now() >= deadline {
            panic!("workspace {ws_name} build did not succeed within {timeout:?}");
        }
        tokio::time::sleep(std::time::Duration::from_secs(3)).await;
    }
}

