    #[test]
    fn build_wait_success_accepts_running_and_job_succeeded() {
        // A successful start is signaled by latest_build.status == "running"
        // and/or latest_build.job.status == "succeeded".
        let running = serde_json::json!({
            "id": "ws-1",
            "latest_build": {"status": "running", "job": {"status": "running"}}
        });
        assert!(build_wait_is_success(&running));
        let job_done = serde_json::json!({
            "id": "ws-2",
            "latest_build": {"status": "starting", "job": {"status": "succeeded"}}
        });
        assert!(build_wait_is_success(&job_done));
        let pending = serde_json::json!({
            "id": "ws-3",
            "latest_build": {"status": "starting", "job": {"status": "pending"}}
        });
        assert!(!build_wait_is_success(&pending));
    }

    /// Pure mirror of the terminal-success logic in
    /// `wait_for_workspace_build_succeeded`.
    fn build_wait_is_success(ws: &Value) -> bool {
        let ws_status = ws
            .get("latest_build")
            .and_then(|b| b.get("status"))
            .and_then(Value::as_str)
            .unwrap_or("");
        let job_status = ws
            .get("latest_build")
            .and_then(|b| b.get("job"))
            .and_then(|j| j.get("status"))
            .and_then(Value::as_str)
            .unwrap_or("");
        job_status == "succeeded" || ws_status == "running"
    }

